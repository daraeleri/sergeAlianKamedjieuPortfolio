const NORTH = 78;
const SOUTH = -57;

/** Position of a place on the map, as percentages of its width and height. */
export function mapPosition(lat: number, lng: number) {
  return {
    left: ((lng + 180) / 360) * 100,
    top: ((NORTH - lat) / (NORTH - SOUTH)) * 100,
  };
}
